export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES];

/**
 * BE-25K — Mobile error categories.
 *
 * A stable, machine-readable classification so mobile clients can branch on
 * category without maintaining the full ERROR_CODES list. Derived from the
 * HTTP status (single mapping — no second error framework).
 */
export const ERROR_CATEGORIES = [
  'VALIDATION',
  'BAD_REQUEST',
  'UNAUTHORIZED',
  'FORBIDDEN',
  'NOT_FOUND',
  'CONFLICT',
  'RATE_LIMITED',
  'SERVER',
] as const;

export type ErrorCategory = (typeof ERROR_CATEGORIES)[number];

/** Maps an error to its mobile category. */
export function categoryForError(
  statusCode: number,
  code: string,
): ErrorCategory {
  if (code === ERROR_CODES.VALIDATION_ERROR) {
    return 'VALIDATION';
  }
  if (statusCode === 401) {
    return 'UNAUTHORIZED';
  }
  if (statusCode === 403) {
    return 'FORBIDDEN';
  }
  if (statusCode === 404) {
    return 'NOT_FOUND';
  }
  if (statusCode === 409) {
    return 'CONFLICT';
  }
  if (statusCode === 429) {
    return 'RATE_LIMITED';
  }
  if (statusCode >= 500) {
    return 'SERVER';
  }
  // Generic client errors (e.g. 400 BAD_REQUEST, 413 payload too large).
  return 'BAD_REQUEST';
}

/**
 * BE-25K — Retryable flag.
 *
 * True when blindly retrying the request is safe and meaningful: server
 * errors (5xx) and rate limiting. Client errors (validation, authorization,
 * not-found, conflict) are NOT retryable — they need a corrected request,
 * a re-login, or a reload (conflict guidance).
 */
export function isRetryableStatus(statusCode: number): boolean {
  return statusCode >= 500 || statusCode === 429;
}

export type AppErrorOptions = {
  code: ErrorCode;
  message: string;
  statusCode: number;
  details?: unknown[];
  /**
   * BE-25K — resource/context reference where useful
   * (e.g. { type: 'CHECKLIST_EXECUTION', id: '…' } on a not-found).
   */
  resource?: { type: string; id: string };
  /**
   * BE-25K — conflict metadata where applicable
   * (e.g. current server state + reload guidance on an immutable-resource
   * rejection). Mirrors the BE-25I sync conflict payload.
   */
  conflict?: unknown;
};

export class AppError extends Error {
  readonly code: ErrorCode;
  readonly statusCode: number;
  readonly details?: unknown[];
  readonly resource?: { type: string; id: string };
  readonly conflict?: unknown;

  constructor(options: AppErrorOptions) {
    super(options.message);
    this.name = 'AppError';
    this.code = options.code;
    this.statusCode = options.statusCode;
    this.details = options.details;
    this.resource = options.resource;
    this.conflict = options.conflict;
  }

  static badRequest(message = 'Bad request.'): AppError {
    return new AppError({
      code: ERROR_CODES.BAD_REQUEST,
      message,
      statusCode: 400,
    });
  }

  static notFound(message = 'Resource not found.'): AppError {
    return new AppError({
      code: ERROR_CODES.NOT_FOUND,
      message,
      statusCode: 404,
    });
  }

  static validation(
    message = 'Request validation failed.',
    details: unknown[] = [],
  ): AppError {
    return new AppError({
      code: ERROR_CODES.VALIDATION_ERROR,
      message,
      statusCode: 400,
      details,
    });
  }

  static databaseUnavailable(
    message = 'Database connection is unavailable.',
  ): AppError {
    return new AppError({
      code: ERROR_CODES.DATABASE_UNAVAILABLE,
      message,
      statusCode: 503,
    });
  }

  static internal(
    message = 'An unexpected server error occurred.',
  ): AppError {
    return new AppError({
      code: ERROR_CODES.INTERNAL_SERVER_ERROR,
      message,
      statusCode: 500,
    });
  }
}
