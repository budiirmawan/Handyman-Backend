function numberValue(value: string | number): number {
  return typeof value === 'number' ? value : Number(value);
}

function mapControlledIssue(
  row: ControlledIssueRow,
): HandymanMaterialControlledIssueRecord {
  return {
    ...row,
    quantity: numberValue(row.quantity),
    inventoryMaterialReservationId: row.inventoryMaterialReservationId ?? null,
    handymanServiceVisitId: row.handymanServiceVisitId ?? null,
    handymanWorkSessionId: row.handymanWorkSessionId ?? null,
    reference: row.reference ?? null,
    notes: row.notes ?? null,
  };
}

function mapActualUsage(row: ActualUsageRow): HandymanMaterialActualUsageRecord {
  return {
    ...row,
    quantity: numberValue(row.quantity),
    handymanMaterialControlledIssueId:
      row.handymanMaterialControlledIssueId ?? null,
    inventoryItemId: row.inventoryItemId ?? null,
    handymanServiceVisitId: row.handymanServiceVisitId ?? null,
    handymanWorkSessionId: row.handymanWorkSessionId ?? null,
    notes: row.notes ?? null,
  };
}

function mapReturn(row: ReturnRow): HandymanMaterialReturnRecord {
  return {
    ...row,
    quantity: numberValue(row.quantity),
    reference: row.reference ?? null,
    notes: row.notes ?? null,
  };
}

