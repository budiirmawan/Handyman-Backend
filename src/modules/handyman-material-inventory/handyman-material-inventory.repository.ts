/** Read only after `lockControlledIssueById`; the lock makes sums stable. */
async function getIssueUseReturnSnapshot(
  executor: Executor,
  handymanMaterialControlledIssueId: string,
): Promise<{ issuedQuantity: number; usedQuantity: number; returnedQuantity: number }> {
  const result = await executor.query<{
    issuedQuantity: string | number;
    usedQuantity: string | number;
    returnedQuantity: string | number;
  }>(
    `SELECT
       i.quantity AS "issuedQuantity",
       COALESCE((
         SELECT SUM(u.quantity)
         FROM handyman_material_actual_usages u
         WHERE u.handyman_material_controlled_issue_id = i.id
       ), 0)::numeric AS "usedQuantity",
       COALESCE((
         SELECT SUM(r.quantity)
         FROM handyman_material_returns r
         WHERE r.handyman_material_controlled_issue_id = i.id
       ), 0)::numeric AS "returnedQuantity"
     FROM handyman_material_controlled_issues i
     WHERE i.id = $1`,
    [handymanMaterialControlledIssueId],
  );
  const row = result.rows[0];
  if (!row) throw new Error('Controlled issue snapshot was not found.');
  return {
    issuedQuantity: numberValue(row.issuedQuantity),
    usedQuantity: numberValue(row.usedQuantity),
    returnedQuantity: numberValue(row.returnedQuantity),
  };
}

/** Read only after the customer-supplied demand lock. */
async function getCustomerActualUsageQuantity(
  executor: Executor,
  handymanMaterialDemandId: string,
): Promise<number> {
  const result = await executor.query<{ quantity: string | number }>(
    `SELECT COALESCE(SUM(quantity), 0)::numeric AS quantity
     FROM handyman_material_actual_usages
     WHERE handyman_material_demand_id = $1
       AND handyman_material_controlled_issue_id IS NULL`,
    [handymanMaterialDemandId],
  );
  return numberValue(result.rows[0]?.quantity ?? 0);
}

