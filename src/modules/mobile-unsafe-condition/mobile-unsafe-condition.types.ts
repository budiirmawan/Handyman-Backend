import type {
  AssetFailureCategory,
  AssetFailureImpact,
  AssetFailureStatus,
} from '../asset-failures';
import type { IncidentStatus } from '../incidents';

/**
 * CR-BE-RN10-SAFE-EQUIPMENT-01 PART 01 — Mobile field-reported unsafe condition.
 *
 * An UNSAFE CONDITION has exactly ONE authoritative representation in the
 * backend: a BE-21C Asset Failure / Defect Incident whose
 * `operationalImpact` is `SAFETY_RISK`. This PART adds NO new entity, NO
 * `unsafe` boolean, NO unsafe Asset or Equipment status, and NO second
 * unsafe-condition table — the controlled BE-21C impact vocabulary already
 * carries the concept (`ASSET_FAILURE_IMPACTS`, mig 0216:
 * `NONE | DEGRADED | PARTIAL_OUTAGE | FULL_OUTAGE | SAFETY_RISK`).
 *
 * This module is a thin mobile FIELD COMMAND over the existing BE-21C
 * authority (`assetFailureService.createAssetFailure`). It composes; it does
 * not re-implement Asset Failure creation, and it duplicates no domain rule.
 *
 * WHAT THIS COMMAND DELIBERATELY DOES NOT DO
 * ------------------------------------------
 *   - it does not touch `assets.status` (BE-05E lifecycle) — recording an
 *     unsafe condition is an operational record, never a lifecycle move;
 *   - it does not touch `equipment_profiles.status` (BE-05D technical sheet);
 *   - it creates no OUT_OF_SERVICE / ISOLATED / SHUT_DOWN state and no
 *     RETURN_TO_SERVICE command — those are later RN-10 PARTs and are ABSENT
 *     from the backend entirely today;
 *   - it does not transition a Work Order or a Finding, and it never derives
 *     a Work Order CRITICAL priority.
 *
 * AUTHORITY SURFACE
 * -----------------
 * The field reporter describes WHAT THEY SAW. Every authoritative field is
 * server-derived, and every management/triage field is rejected rather than
 * ignored — silently dropping a caller's `failureStatus` would hide that
 * their intent was not honoured (the same posture BE-21C's own
 * `parseCreateAssetFailureBody` takes for `incidentType`).
 *
 * Server-derived, never accepted from the body:
 *   assetId, clientId, buildingId, incidentNumber, incidentType,
 *   operationalImpact, failureStatus, incidentStatus, reportedByUserId,
 *   createdByUserId, severity, priority, location*.
 */

/** The BE-21C impact that IS the authoritative unsafe-condition marker. */
export const UNSAFE_CONDITION_OPERATIONAL_IMPACT = 'SAFETY_RISK' as const;

/** The BE-21C failure-handling status every new report starts in. */
export const UNSAFE_CONDITION_INITIAL_FAILURE_STATUS = 'OPEN' as const;

/**
 * The ONLY body keys this command accepts.
 *
 * These are the smallest existing BE-21C human-entered narrative fields, named
 * exactly as BE-21C names them — no aliases are invented:
 *   `title`           the required human narrative / reason (≤200),
 *   `description`     optional elaboration (≤4000),
 *   `failureCategory` optional controlled observation code (defaults to the
 *                     existing `OTHER` escape hatch when the reporter does not
 *                     classify),
 *   `occurredAt`      optional observation instant; defaults to the server
 *                     report time. Never post-dated (BE-21C `assertOccurrence`).
 *
 * `failureCategory` is an OBSERVATION the technician is best placed to make
 * ("leakage", "overheating"); it is not triage authority. `severity` and
 * `priority` are deliberately NOT accepted: triage stays management authority
 * on the existing BE-21C update path, so RN-10 cannot drift into inferring
 * CRITICAL from a field report.
 */
export const MOBILE_UNSAFE_CONDITION_BODY_FIELDS = [
  'title',
  'description',
  'failureCategory',
  'occurredAt',
] as const;

export type MobileUnsafeConditionBodyField =
  (typeof MOBILE_UNSAFE_CONDITION_BODY_FIELDS)[number];

