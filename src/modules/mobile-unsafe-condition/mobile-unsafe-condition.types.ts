/** The accepted request body after validation. Timestamps are already parsed. */
export type MobileUnsafeConditionInput = {
  title: string;
  description?: string | null;
  failureCategory?: AssetFailureCategory;
  occurredAt?: Date;
};

/**
 * The reporting acknowledgement.
 *
 * Deliberately NOT the full `PublicAssetFailure` projection: that view carries
 * backend-authoritative `availableActions` resolved from `asset_failure.manage`,
 * which a field reporter does not hold and which would therefore always be
 * empty — an empty action list on a write response is a contract lie waiting to
 * be read as "nothing is possible". The canonical post-mutation read stays
 * `GET /asset-failures/{incidentId}` (the `incidentId` returned here is the
 * shared BE-21A identity that route addresses).
 */
export type MobileUnsafeConditionReported = {
  /** Shared BE-21A Incident id — the canonical read/address id. */
  incidentId: string;
  incidentNumber: string;
  assetId: string;
  clientId: string;
  buildingId: string;
  /**
   * Pinned to the literal `SAFETY_RISK`. Typed as the literal rather than as
   * the wide `AssetFailureImpact` union because this command SETS it — it is
   * not read back from the record, so the narrower type is the truthful one.
   */
  operationalImpact: typeof UNSAFE_CONDITION_OPERATIONAL_IMPACT;
  failureCategory: AssetFailureCategory;
  /**
   * Read back from the record. BE-21C starts every new failure at `OPEN`; the
   * value is NOT asserted here, and the contract test pins it to `OPEN` at
   * runtime so a change in the domain default cannot pass silently.
   */
  failureStatus: AssetFailureStatus;
  /** Read back from the record. BE-21A starts every new Incident at `REPORTED`. */
  incidentStatus: IncidentStatus;
  occurredAt: string;
  /** The authenticated caller — never a body field. */
  reportedByUserId: string;
  reportedAt: string;
  createdAt: string;
  /** The read to re-fetch the canonical record after this mutation. */
  canonicalRead: {
    operationId: 'getAssetFailure';
    path: string;
  };
};
