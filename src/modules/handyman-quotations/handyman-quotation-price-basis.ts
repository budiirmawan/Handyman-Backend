import type { PoolClient } from 'pg';
import { withTransaction } from '../../database';
import { AppError } from '../../shared/errors';
import { isValidUuid } from '../clients';
import { assertHandymanQuotationPricingAuthority, assertQuotationThreadBuildingAccess } from './handyman-quotation-access';
import { handymanQuotationRepository } from './handyman-quotation.repository';
import { handymanQuotationNotFoundError, handymanQuotationVersionNotDraftError, handymanQuotationVersionNotFoundError } from './handyman-quotation.errors';

/** This is a customer-facing commercial term, not a tax classification or a
 * Finance-approved rate. It never changes a quoted amount. */
export const QUOTATION_PRICE_BASIS_PROTOCOL = 'HANDYMAN_QUOTATION_LINE_PRICE_BASIS_V1' as const;
export const VARIATION_PRICE_BASIS_PROTOCOL = 'HANDYMAN_VARIATION_LINE_PRICE_BASIS_V1' as const;
export const HANDYMAN_TAX_PRICE_BASES = ['GROSS_INCLUSIVE', 'TAX_EXCLUSIVE'] as const;
export type HandymanTaxPriceBasis = (typeof HANDYMAN_TAX_PRICE_BASES)[number];

export function parseTaxPriceBasis(value: unknown): HandymanTaxPriceBasis {
  if (typeof value !== 'string' || !(HANDYMAN_TAX_PRICE_BASES as readonly string[]).includes(value)) {
    throw AppError.validation('taxPriceBasis must be GROSS_INCLUSIVE or TAX_EXCLUSIVE.');
  }
  return value as HandymanTaxPriceBasis;
}

export function taxPriceBasisLabel(basis: HandymanTaxPriceBasis | undefined): string {
  if (basis === 'GROSS_INCLUSIVE') return 'INCLUSIVE - includes applicable PPN / termasuk PPN yang berlaku';
  if (basis === 'TAX_EXCLUSIVE') return 'EXCLUSIVE - excludes applicable PPN / belum termasuk PPN yang berlaku';
  return 'NOT DISCLOSED in historical offer / tidak dinyatakan dalam penawaran lama';
}

/** Called only under the version lock, after the existing pricing authority. */
export async function writeDraftLinePriceBasis(tx: PoolClient, versionId: string, lineId: string,
  basis: HandymanTaxPriceBasis, actorUserId: string): Promise<void> {
  const result = await tx.query(`INSERT INTO handyman_quotation_line_price_bases
    (quotation_line_id,quotation_version_id,tax_price_basis,authored_by_user_id)
    SELECT l.id,l.quotation_version_id,$3,$4 FROM handyman_quotation_lines l
    WHERE l.id=$2 AND l.quotation_version_id=$1
    ON CONFLICT (quotation_line_id) DO UPDATE SET tax_price_basis=EXCLUDED.tax_price_basis,
      authored_by_user_id=EXCLUDED.authored_by_user_id,updated_at=clock_timestamp()
    RETURNING quotation_line_id`, [versionId, lineId, basis, actorUserId]);
  if (!result.rowCount) throw AppError.notFound('Quotation line not found in the requested version.');
}

/** Supports pre-existing/autogenerated DRAFT lines without altering their price. */
export async function setHandymanQuotationLineTaxPriceBasis(versionId: string, lineId: string,
  value: unknown, actorUserId: string) {
  if (![versionId, lineId, actorUserId].every(isValidUuid)) throw AppError.validation('Valid quotation, line and actor IDs are required.');
  const taxPriceBasis = parseTaxPriceBasis(value);
  return withTransaction(async tx => {
    const version = await handymanQuotationRepository.lockVersionById(tx, versionId);
    if (!version) throw handymanQuotationVersionNotFoundError();
    const quotation = await handymanQuotationRepository.findQuotationById(tx, version.quotationId);
    if (!quotation) throw handymanQuotationNotFoundError();
    await assertQuotationThreadBuildingAccess(tx as never, quotation, actorUserId);
    await assertHandymanQuotationPricingAuthority({ clientId: quotation.clientId,
      handymanRequestId: quotation.handymanRequestId, actorUserId }, tx);
    if (version.status !== 'DRAFT') throw handymanQuotationVersionNotDraftError();
    await writeDraftLinePriceBasis(tx, version.id, lineId, taxPriceBasis, actorUserId);
    return { quotationVersionId: version.id, quotationLineId: lineId, taxPriceBasis };
  });
}
